-- CORREÇÃO DA TRANSAÇÃO
-- A TRANSAÇÃO FUNCIONA POR ETAPAS SE UMA DELAS FALHAR O PROCESSO PODE GERAR INCOSISTÊNCIA

-- SEM TRANSAÇÃO - PARTE DO PROCESSO PERMANECE GRAVADO
-- COM TRANSAÇÃO - PODEMOS CONFIRMAR OU DESFAZER TUDO

-- SINTAXE DE TRANSAÇÃO
START TRANSACTION;
INSERT ...
UPDATE ...
INSERT ...
SELECT ...
COMMIT;
-- MODELO DE FUNCIONAMENTO DA TCL 

-- EX 1 - COMMIT CONFIRMA ALTERAÇÕES REALIZADAS DENTRO DA TRANSAÇÃO 
START TRANSACTION;
UPDATE produto
SET PRECO = 9.00
WHERE ID_PRODUTO = 64

SELECT NOME, PRECO FROM PRODUTO;
SELECT ID_PRODUTO FROM produto;

COMMIT;

-- EX 2 - ROLLBACK - DESFAZ AS ALTERAÇÕES AINDA NÃO CONFIRMADAS
START TRANSACTION;
UPDATE produto
SET PRECO = 50.00
WHERE id_produto = 64;

SELECT NOME, PRECO FROM produto;

ROLLBACK;
COMMIT;

-- EX 3 - SAVEPOINT - PONTO DE SALVAMENTO
START TRANSACTION;

UPDATE produto
SET PRECO = PRECO * 1.05
WHERE id_categoria = 1;

SAVEPOINT REAJUSTE_CAFES;
COMMIT;

-- EX 4 - RELEASE SAVEPOINT: LIBERAR ESPAÇO GRAVADO
RELEASE SAVEPOINT REAJUSTE_CAFES;

-- CONSTRAINT - NÃO SUBSTITUI TRANSAÇÃO
-- TRANSAÇÃO: CONSTROLA UM CONJUNTO DE OPERAÇÕES
-- CONSTRAINT: IMPEDE QUE DETERMINAMOS VALORES INVÁLIDOS SEJAM ACEITOS

-- EX 0 - NÃO ATUALIZA OU RESTRINGE VALORES NEGATIVOS
CONSTRAINT CK_ESTOQUE_QUANTIDADE CHECK (QUANTIDADE >= 0);

--  EX 1 - INTEGRIDADE REFERENCIAL
CONSTRAINT FK_PEDIDO_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE (ID_CLIENTE);
-- A FK OU CHAVE ESTRANGEIRA IRÁ IMPEDIR QUE O PEDIDO APONTE OU REALIZE UM CLIENTE QUE NÃO EXISTE

-- EX 2 - ON DELETE
-- RESTRIC: BLOQUEIA EXCLUSÃO COM DEPENDENTES
-- CASCADE: EXCLUI DEPENDENTES
-- SET NULL: REMOVE REFERÊNCIA
CONSTRAINT FK_ITEM_PEDIDO FOREIGN KEY (ID_PEDIDO) REFERENCES PEDIDO (ID_PEDIDO) ON DELETE RESTRICT;
-- OBS: IMPORTANTE LEMBRAR DESSES CONCEITOS

-- EX 3 - ON UPDATE 
-- DEFINE QUE OCORRE COM FKS QUANDO A CHAVE REFERENCIADA É ALTERADA
CONSTRAINT FK_ITEM_PEDIDO FOREIGN KEY (ID_PEDIDO) REFERENCES PEDIDO (ID_PEDIDO) ON DELETE RESTRICT ON UPDATE CASCADE;

-- EX 4 - EXCLUSÃO FÍSICA E LÓGICA
-- FÍSICA
DELETE FROM produto WHERE id_produto = 10;

